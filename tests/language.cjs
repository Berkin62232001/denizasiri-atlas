const fs = require('node:fs');
const assert = require('node:assert/strict');
const { loadAtlas } = require('../qa-atlas.cjs');
const html = fs.readFileSync('outputs/Yeryuzu-Atlasi.html', 'utf8');
const options = {url:'https://atlas.example/', pretendToBeVisual:true};
const dom = loadAtlas(html, options);
const {document:d, localStorage} = dom.window;
const get = id => d.getElementById(id);
const choose = lang => d.querySelector('#language-switch input[value="' + lang + '"]').click();

assert.equal(d.documentElement.lang, 'tr');
get('compare-toggle').click();
const years = ['compare-left-year', 'compare-right-year'].map(id => get(id).value);
const target = d.querySelector('#map-right [data-region]');
target.dispatchEvent(new dom.window.MouseEvent('click', {bubbles:true, detail:1}));
assert.equal(get('map-popup').hidden, false);
const turkishBody = get('event-body').textContent;
choose('en');
assert.equal(d.documentElement.lang, 'en');
assert.equal(d.querySelector('.map-caption').textContent, 'Approximate boundaries');
assert.equal(get('popup-close').getAttribute('aria-label'), 'Close details');
assert.equal(get('map-popup').hidden, false);
assert.notEqual(get('event-body').textContent, turkishBody);
assert.deepEqual(['compare-left-year', 'compare-right-year'].map(id => get(id).value), years);
assert.equal(localStorage.getItem('atlas.language'), 'en');
choose('tr');
assert.equal(get('event-body').textContent, turkishBody);
assert.equal(d.querySelector('.map-caption').textContent, 'Yaklaşık sınırlar');
get('compare-toggle').click();
get('modern-provinces').click();
const province = dom.window.ATLAS_PROVINCES.findIndex(row => row[4] && row[0] !== row[4]);
assert.ok(province >= 0);
const provinceNames = dom.window.ATLAS_PROVINCES[province];
const shape = d.querySelector('[data-province="' + province + '"]');
shape.dispatchEvent(new dom.window.MouseEvent('click', {bubbles:true, detail:1}));
assert.equal(get('event-title').textContent, provinceNames[0]);
choose('en');
assert.equal(get('event-title').textContent, provinceNames[4]);
assert.ok(get('province-options').options[province].value.startsWith(provinceNames[4] + ' · '));
setImmediate(() => dom.window.close());

const saved = loadAtlas(html, {...options, beforeParse(window) {
  window.localStorage.setItem('atlas.language', 'en');
}});
assert.equal(saved.window.document.documentElement.lang, 'en');
assert.ok(saved.window.document.querySelector('input[value="en"]').checked);
assert.equal(saved.window.document.title, 'World Atlas — The Colonial Era');
saved.window.close();
console.log('Language switching, persistence and comparison popup state passed.');
