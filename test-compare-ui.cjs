const { JSDOM } = require('./qa/node_modules/jsdom');
const fs = require('fs');
const assert = require('node:assert/strict');
const read = file => fs.readFileSync(__dirname + '/' + file, 'utf8');
const dom = require('./qa-atlas.cjs').loadAtlas(read('dist/index.html'), {pretendToBeVisual:true});
const {window}=dom;
const get=id=>window.document.getElementById(id);
const change = (id, value) => {
  get(id).value = value;
  get(id).dispatchEvent(new window.Event('change'));
};
const click = id => get(id).click();
assert.equal(get('year').value, '1402');
assert.ok(get('compare-years').hidden);
click('compare-toggle');
assert.deepEqual([get('year').value, get('compare-left-year').value, get('compare-right-year').value], ['1878','1878','1914']);
assert.ok(!get('map-right').hasAttribute('hidden'));
assert.equal(get('compare-toggle').getAttribute('aria-pressed'), 'true');
const rightTarget = get('map-right').querySelector('path[data-region], g[data-region]');
assert.ok(rightTarget);
rightTarget.dispatchEvent(new window.MouseEvent('click', { bubbles: true, detail: 1 }));
assert.equal(get('map-popup').hidden, false);
assert.match(get('event-body').textContent, /Sağ harita · 1914/);
const leftTarget = get('map').querySelector('path[data-region], g[data-region]');
leftTarget.dispatchEvent(new window.MouseEvent('click', { bubbles: true, detail: 1 }));
assert.match(get('event-body').textContent, /Sol harita · 1878/);
change('compare-left-year', 1938);
change('compare-right-year', 1957);
assert.equal(get('year').value, '1938');
assert.equal(get('compare-right-year').value, '1957');
get('compare-divider').value = '64';
get('compare-divider').dispatchEvent(new window.Event('input'));
assert.equal(get('map-right').style.clipPath, 'inset(0 0 0 64%)');
assert.equal(get('map').style.clipPath, 'inset(0 36% 0 0)');
click('compare-toggle');
assert.equal(get('year').value, '1402');
assert.ok(get('map-right').hasAttribute('hidden'));
assert.ok(get('compare-overlay').hidden);
assert.equal(get('map').style.clipPath, '');
change('year', 2026);
click('un-layer');
assert.ok(get('un-layer').checked);
click('compare-toggle');
assert.ok(get('un-panel').hidden);
assert.ok(get('modern-provinces').disabled);
click('compare-toggle');
assert.equal(get('year').value, '2026');
assert.ok(get('un-layer').checked);
assert.equal(get('map').querySelectorAll('g[data-region]').length, 17);
console.log('Comparison UI verified: samples, independent years, dates on both sides, divider, normal year and UN restored.');
window.close();
